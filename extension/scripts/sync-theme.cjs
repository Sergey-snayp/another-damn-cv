const fs = require('node:fs');
const path = require('node:path');

// The web app owns the palette; the extension packages a generated copy for standalone use.
const source = path.resolve(__dirname, '../../frontend/src/theme/colors.css');
const header = '/* Generated by extension/scripts/sync-theme.cjs. Edit frontend/src/theme/colors.css. */\n';
const palette = fs.readFileSync(source, 'utf8');

for (const [name, body] of [['colors.css', palette], ['launcher-colors.css', palette.replace(/:root\b/g, ':host')]]) {
  const target = path.resolve(__dirname, '../assets/theme', name);
  const content = header + body;
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}
